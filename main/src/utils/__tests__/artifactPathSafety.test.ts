import { describe, it, expect } from 'vitest';
import * as path from 'path';
import { isSafeSessionId, getSafeImageExtension } from '../artifactPathSafety';

describe('isSafeSessionId', () => {
  it('accepts a real session id (crypto.randomUUID format)', () => {
    expect(isSafeSessionId('3fa85f64-5717-4562-b3fc-2c963f66afa6')).toBe(true);
  });

  it('accepts a pending session id generated by the renderer', () => {
    expect(isSafeSessionId('pending_1700000000000_abc1234')).toBe(true);
  });

  it('rejects a session id containing a path traversal sequence', () => {
    expect(isSafeSessionId('pending_../../../../../../tmp/evilsession')).toBe(false);
  });

  it('rejects a session id containing a path separator', () => {
    expect(isSafeSessionId('foo/bar')).toBe(false);
    expect(isSafeSessionId('foo\\bar')).toBe(false);
  });

  it('rejects empty or non-string input', () => {
    expect(isSafeSessionId('')).toBe(false);
    // @ts-expect-error intentionally testing bad input
    expect(isSafeSessionId(undefined)).toBe(false);
  });

  it('never allows the resulting joined path to escape the parent directory', () => {
    const base = path.join('/tmp', 'crystal-artifacts-test');
    const maliciousId = '../../../../../../etc';
    expect(isSafeSessionId(maliciousId)).toBe(false);
    // Demonstrate why: if it were allowed, join would escape `base`.
    const joined = path.join(base, 'artifacts', maliciousId);
    expect(joined.startsWith(base)).toBe(false);
  });
});

describe('getSafeImageExtension', () => {
  it('maps known mime types to their expected extension', () => {
    expect(getSafeImageExtension('image/png')).toBe('png');
    expect(getSafeImageExtension('image/jpeg')).toBe('jpg');
    expect(getSafeImageExtension('image/gif')).toBe('gif');
    expect(getSafeImageExtension('image/webp')).toBe('webp');
  });

  it('falls back to png for an unknown mime type', () => {
    expect(getSafeImageExtension('image/x-made-up')).toBe('png');
  });

  it('falls back to png for a mime type crafted for path traversal', () => {
    const malicious = 'image/../../../../../../tmp/pwned.sh';
    expect(getSafeImageExtension(malicious)).toBe('png');
  });

  it('falls back to png for missing/undefined mime type', () => {
    expect(getSafeImageExtension(undefined)).toBe('png');
    expect(getSafeImageExtension(null)).toBe('png');
    expect(getSafeImageExtension('')).toBe('png');
  });
});
