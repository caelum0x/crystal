/**
 * Safety helpers for building file-system paths from IPC input when saving
 * session artifacts (pasted images / large text blobs).
 *
 * `sessions:save-images` and `sessions:save-large-text` build a directory
 * from the caller-supplied `sessionId` and (for images) a file extension
 * derived from a caller-supplied MIME `type`. Neither value is guaranteed to
 * come from a trusted source once it crosses the IPC boundary, so both must
 * be validated before being used in `path.join(...)`.
 */

// Real sessions use crypto.randomUUID(); pending (not-yet-created) sessions
// use `pending_<timestamp>_<randomBase36>` generated by the renderer.
const SAFE_SESSION_ID_PATTERN = /^[A-Za-z0-9_-]+$/;

/**
 * Returns true only if `sessionId` is a plain identifier containing no path
 * separators, `..` traversal segments, or other characters that could
 * escape the intended artifacts directory when joined with a base path.
 */
export function isSafeSessionId(sessionId: string): boolean {
  if (!sessionId || typeof sessionId !== 'string') {
    return false;
  }
  return SAFE_SESSION_ID_PATTERN.test(sessionId);
}

const ALLOWED_IMAGE_EXTENSIONS: Record<string, string> = {
  'image/png': 'png',
  'image/jpeg': 'jpg',
  'image/jpg': 'jpg',
  'image/gif': 'gif',
  'image/webp': 'webp',
  'image/bmp': 'bmp',
  'image/svg+xml': 'svg',
};

/**
 * Derives a safe file extension for a saved image from its MIME `type`.
 * Falls back to `png` for anything not on the allow-list, which also
 * neutralizes attempts to smuggle path separators or traversal sequences
 * in via a crafted `type` value (e.g. `image/../../../../etc/cron.d/x`).
 */
export function getSafeImageExtension(mimeType: string | undefined | null): string {
  if (!mimeType) {
    return 'png';
  }
  return ALLOWED_IMAGE_EXTENSIONS[mimeType.toLowerCase()] ?? 'png';
}
